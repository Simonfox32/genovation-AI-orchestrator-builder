"""Connects the backend to the orchestrator. This is the only file that knows about orchestrator code.

Flow for one project:  decompose (orchestrator/decomposer.py) -> route each module (orchestrator/router.py)
-> save each result as a task.

What is real depends on configuration:
  - GEMINI_API_KEY set:    the plan comes from Gemini; otherwise it's a fixed sample module (TEST DATA).
  - ROUTER_TOOLS=real:     the router asks Gemini to write each module's code; otherwise it uses
                           simulated tools that return hard-coded code.
"""
import logging
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from uuid import UUID, uuid4

# orchestrator/ lives beside backend/, so put the repo root on the import path.
# Revisit when deploying: the deployed service must include the orchestrator/ folder.
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from orchestrator import decomposer, router  # noqa: E402  (must come after the sys.path change)

from models import Project, Task  # noqa: E402

logger = logging.getLogger(__name__)

# The router reports "passed"/"failed"; the API and database use the shared status vocabulary.
ROUTER_STATUS_TO_TASK_STATUS = {"passed": "completed", "failed": "failed"}


def get_llm():
    """The LLM function the decomposer should use, or None for the fixed sample plan.

    Imported only when a key is set, so the backend still runs without Google's library configured.
    """
    if not os.getenv("GEMINI_API_KEY"):
        return None
    from orchestrator.llm import call_llm

    def plan_llm(prompt):
        return call_llm(prompt, json_mode=True)  # the plan must be valid JSON

    return plan_llm


def describe_plan(used_llm: bool) -> str:
    """Honest summary shown in the dashboard: where the plan and the code came from."""
    plan = (
        "Plan generated by Gemini from your description."
        if used_llm
        else "SAMPLE PLAN (test data): no AI model is configured, so every project gets the same sample module."
    )
    tools = (
        "Code is written by Gemini and checked against each module's test."
        if os.getenv("ROUTER_TOOLS") == "real"
        else "Code comes from simulated tools (no AI model is called)."
    )
    return plan + " " + tools


def run_pipeline(project_id: UUID, session_factory) -> None:
    """Process one project in the background. Never raises: failures mark the project as failed."""
    db = session_factory()
    try:
        project = db.get(Project, project_id)
        if project is None:
            logger.warning("Pipeline started for missing project %s", project_id)
            return

        llm = get_llm()
        # An LLM error or an invalid plan raises here, and the except below marks the project failed.
        modules = decomposer.decompose(project.description, project.optimization, llm=llm)
        project.status = "running"
        project.summary = describe_plan(used_llm=llm is not None)
        project.tasks = [
            Task(id=uuid4(), position=position, name=module["name"], description=module.get("description"))
            for position, module in enumerate(modules, start=1)
        ]
        _touch(project)
        db.commit()

        delay = float(os.getenv("DEMO_STEP_DELAY_SECONDS", "1"))  # DEMO ONLY: makes progress visible in the UI
        for task, module in zip(project.tasks, modules):
            task.status = "running"
            _touch(project)
            db.commit()
            time.sleep(delay)

            result = router.route(module, project.optimization)
            task.tool = result["tool_used"]
            task.attempts = result["tries"]
            task.status = ROUTER_STATUS_TO_TASK_STATUS[result["status"]]
            task.output = result.get("code")
            _touch(project)
            db.commit()

        project.status = "completed"
        _touch(project)
        db.commit()
    except Exception:
        # Full details go to the server log only; the API just reports status "failed".
        logger.exception("Pipeline failed for project %s", project_id)
        db.rollback()
        _mark_failed(db, project_id)
    finally:
        db.close()


def get_pipeline():
    """Dependency so tests can swap the pipeline out."""
    return run_pipeline


def _touch(project: Project) -> None:
    project.updated_at = datetime.now(timezone.utc)


def _mark_failed(db, project_id: UUID) -> None:
    try:
        project = db.get(Project, project_id)
        if project is not None:
            project.status = "failed"
            _touch(project)
            db.commit()
    except Exception:
        logger.exception("Could not mark project %s as failed", project_id)
        db.rollback()
