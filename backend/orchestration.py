"""Connects the backend to the orchestrator. This is the only file that knows about orchestrator code.

Flow for one project:  decompose (orchestrator/decomposer.py) -> route each module (orchestrator/router.py)
-> save each result as a task.

What is real depends on configuration:
  - GEMINI_API_KEY set:    the plan comes from Gemini; otherwise it's a fixed sample module (TEST DATA).
  - ROUTER_TOOLS=real:     the router asks Gemini to write each module's code; otherwise it uses
                           simulated tools that return hard-coded code.
"""
import json
import logging
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from uuid import UUID, uuid4
import shutil
import tempfile
import threading


# orchestrator/ lives beside backend/, so put the repo root on the import path.
# Revisit when deploying: the deployed service must include the orchestrator/ folder.
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from orchestrator import agent, decomposer, router  # noqa: E402  (must come after the sys.path change)
from orchestrator.executors import LocalExecutor, SandboxExecutor  # noqa: E402

from models import Project, Task  # noqa: E402

logger = logging.getLogger(__name__)

# The router reports "passed"/"failed"; the API and database use the shared status vocabulary.
ROUTER_STATUS_TO_TASK_STATUS = {"passed": "completed", "failed": "failed"}

# Agent projects run one at a time in this process (see run_agent_pipeline). One uvicorn process on Railway,
# so a process-level lock is enough; several processes would need a database-level queue instead.
AGENT_SLOT = threading.Semaphore(1)


def get_llm():
    """The LLM function the decomposer should use, or None for the fixed sample plan.

    Imported only when a key is set, so the backend still runs without Google's library configured.
    """
    if not os.getenv("GEMINI_API_KEY"):
        return None
    from orchestrator.llm import call_llm

    def plan_llm(prompt):
        return call_llm(prompt, json_mode=True)  # the plan must be valid JSON

    return plan_llm


def describe_plan(used_llm: bool) -> str:
    """Honest summary shown in the dashboard: where the plan and the code came from."""
    plan = (
        "Plan generated by Gemini from your description."
        if used_llm
        else "SAMPLE PLAN (test data): no AI model is configured, so every project gets the same sample module."
    )
    tools = (
        "Code is written by Gemini and checked against each module's test."
        if os.getenv("ROUTER_TOOLS") == "real"
        else "Code comes from simulated tools (no AI model is called)."
    )
    return plan + " " + tools


def run_pipeline(project_id: UUID, session_factory) -> None:
    """Process one project in the background. Never raises: failures mark the project as failed."""
    db = session_factory()
    try:
        project = db.get(Project, project_id)
        if project is None:
            logger.warning("Pipeline started for missing project %s", project_id)
            return

        llm = get_llm()
        # An LLM error or an invalid plan raises here, and the except below marks the project failed.
        modules = decomposer.decompose(project.description, project.optimization, llm=llm)
        project.status = "running"
        project.summary = describe_plan(used_llm=llm is not None)
        project.tasks = [
            Task(id=uuid4(), position=position, name=module["name"], description=module.get("description"))
            for position, module in enumerate(modules, start=1)
        ]
        _touch(project)
        db.commit()

        delay = float(os.getenv("DEMO_STEP_DELAY_SECONDS", "1"))  # DEMO ONLY: makes progress visible in the UI
        for task, module in zip(project.tasks, modules):
            task.status = "running"
            _touch(project)
            db.commit()
            time.sleep(delay)

            result = router.route(module, project.optimization)
            task.tool = result["tool_used"]
            task.attempts = result["tries"]
            task.status = ROUTER_STATUS_TO_TASK_STATUS[result["status"]]
            task.output = result.get("code")
            _touch(project)
            db.commit()

        project.status = "completed"
        _touch(project)
        db.commit()
    except Exception:
        # Full details go to the server log only; the API just reports status "failed".
        logger.exception("Pipeline failed for project %s", project_id)
        db.rollback()
        _mark_failed(db, project_id)
    finally:
        db.close()


def make_executor(workspace: Path):
    """WHERE the agents' code runs, picked by EXECUTOR.

    "vercel": a Vercel Sandbox microVM with no secrets and no network. The only safe choice on a public server.
    anything else: this machine. Fine for local development and tests, but NOT a sandbox.
    """
    if os.getenv("EXECUTOR") == "vercel":
        return SandboxExecutor()
    return LocalExecutor(workspace)


def run_agent_pipeline(project_id: UUID, session_factory, with_tester: bool = False) -> None:
    """Let the coding agent build the starter app; save every step as a task so the dashboard shows it live.

    ORCHESTRATOR=agent (with_tester=False): the builder works against the built-in todo tests. The user's
    description is stored but never given to an agent, so no user text steers code that runs on this server.

    ORCHESTRATOR=agent-team (with_tester=True): a tester agent first writes tests from the user's description,
    then the builder makes them pass. Here user text DOES steer the code that gets run.

    Where that code runs is make_executor's choice: with EXECUTOR=vercel it runs in a Vercel Sandbox microVM
    (no secrets, no network), the only safe setting for a public server. Without it, it runs on this machine.

    Never raises: failures mark the project as failed.
    """
    db = session_factory()
    workspace_root = Path(tempfile.mkdtemp(prefix="agent-"))
    holding_slot = False
    executor = None
    meter = None

    try:
        project = db.get(Project, project_id)
        if project is None:
            logger.warning("Agent pipeline started for missing project %s", project_id)
            return

        # One agent project at a time: two at once exceed the free Gemini tier's per-minute limit (429s).
        if not AGENT_SLOT.acquire(blocking=False):
            project.summary = ("Queued: another project is being built right now. The free Gemini tier allows "
                               "one at a time; this one starts as soon as it finishes.")
            _touch(project)
            db.commit()
            AGENT_SLOT.acquire()  # wait our turn
        holding_slot = True

        workspace = workspace_root / "workspace"  # only used by the local executor
        model = agent.model_for(project.optimization)  # Fastest / Balanced / Best Quality -> cheap / medium / strong
        tester = None
        meter = agent.model_client.UsageMeter.for_project()  # tokens, cost and spending limit across every agent
        executor = make_executor(workspace)
        # Team mode: the database starter, and the tester writes its own tests. Otherwise: the todo app + its tests.
        agent.seed_workspace(executor, include_tests=not with_tester,
                             template=agent.TEMPLATE_DB if with_tester else agent.TEMPLATE)
        if with_tester:
            what = "your backend"
            project.summary = (f"Two AI agents ({model}) are working: a tester is writing tests from your "
                               "description; then a developer builds the backend until they pass.")
        else:
            what = "a todo API"
            requirements = f"Requirements: the built-in todo API test suite ({_count_tests(executor)} tests)."
            project.summary = f"An AI agent ({model}) is building a todo API. {requirements}"
        project.status = "running"
        _touch(project)
        db.commit()

        def make_saver(label="", tester=False):
            """A callback for one agent: one task row per tool call, committed right away so the dashboard shows it."""
            def save_step(event):
                name, output = _describe_step(event)
                project.tasks.append(Task(
                    id=uuid4(), position=len(project.tasks) + 1, name=(label + name)[:200],
                    description=f"Agent step {event['step']}", tool=event["tool"][:50],
                    status=_step_status(event, tester=tester), attempts=1, output=output,
                ))
                _touch(project)
                db.commit()
            return save_step

        if with_tester:
            tester = agent.run_agent(workspace, on_step=make_saver("Tester · ", tester=True), role="tester",
                                     start_message=agent.tester_message(project.description),
                                     max_steps=agent.tester_steps(project.description),
                                     model=model, executor=executor, meter=meter)
            if not tester["passed"]:
                project.tasks.append(Task(
                    id=uuid4(), position=len(project.tasks) + 1,
                    name="The tester agent could not produce valid tests", description=tester["summary"],
                    tool="pytest", status="failed", attempts=1, output=tester["test_output"][-2000:],
                ))
                _save_usage(project, meter)
                project.status = "failed"
                project.summary = ("The tester agent could not turn the description into valid tests "
                                   f"({tester['summary']}). Try a more concrete description.")
                project.artifact = _collect_files(executor)  # downloadable even when it failed
                _touch(project)
                db.commit()
                return
            requirements = (f"Requirements: {_count_requirements(executor)} listed by the tester agent from your "
                            f"description, covered by {_count_tests(executor)} tests.")
            project.summary = f"The tester wrote the requirements; a developer agent is now building {what}. {requirements}"
            _touch(project)
            db.commit()

        saved_tests = agent.save_tests(executor)  # our own copy, taken before any generated app code has run
        outcome = agent.run_agent(workspace, on_step=make_saver("Builder · " if with_tester else ""),
                                  max_steps=agent.builder_steps(agent.count_test_functions(saved_tests))
                                  if with_tester else 15, model=model, executor=executor,
                                  system_prompt=agent.BUILDER_DB_PROMPT if with_tester else None,
                                  reviewable=with_tester, meter=meter)

        if with_tester:
            # The feedback loop: if the builder is stuck, the tester re-checks the failing tests (C4).
            def save_note(text, output=""):
                project.tasks.append(Task(
                    id=uuid4(), position=len(project.tasks) + 1, name=f"Orchestrator · {text}"[:200],
                    description="A decision by the orchestrator", tool="orchestrator", status="completed",
                    attempts=1, output=output[-2000:] or None,
                ))
                _touch(project)
                db.commit()

            outcome = agent.review_rounds(workspace, executor, outcome, model=model, on_note=save_note,
                                          step_logger=lambda label, role: make_saver(label, tester=role == "tester"),
                                          saved_tests=saved_tests, meter=meter)
        outcome = agent.verify_outcome(executor, saved_tests, outcome)  # never take an agent's word for it
        agents = "AI agents" if with_tester else "An AI agent"
        models = _model_note(model, *([tester] if tester else []), outcome, *outcome.get("reviews", []))
        reviews = _review_note(outcome.get("reviews", []))

        # The orchestrator's own verdict, from its own test run (not the agent's claim).
        verdict = _last_line(outcome["test_output"])
        project.tasks.append(Task(
            id=uuid4(), position=len(project.tasks) + 1, name=f"Verified by the orchestrator: {verdict}"[:200],
            description="Final test run by the orchestrator itself", tool="pytest",
            status="completed" if outcome["passed"] else "failed", attempts=1,
            output=outcome["test_output"][-2000:],
        ))
        _save_usage(project, meter)
        if outcome["passed"]:
            project.status = "completed"
            project.summary = (f"{agents} ({models}) built {what} in {outcome['steps']} steps. "
                               f"Verified by our own test run: {verdict}. {requirements}{reviews}")
        else:
            project.status = "failed"
            project.summary = (f"The developer agent ({models}) did not get all tests passing: "
                               f"{outcome['summary']}. Last test run: {verdict}. {requirements}{reviews}")
        # Save every file now: the sandbox (and everything in it) is destroyed when the run ends.
        project.artifact = _collect_files(executor)
        _touch(project)
        db.commit()
        
    except Exception as error:
        logger.exception("Agent pipeline failed for project %s", project_id)
        db.rollback()
        _mark_failed(db, project_id, error, executor, meter)
    finally:
        if executor is not None:
            try:
                executor.close()  # destroys the Vercel sandbox; does nothing for the local executor
            except Exception:
                logger.exception("Could not close the executor for project %s", project_id)
        if holding_slot:
            AGENT_SLOT.release()
        db.close()
        shutil.rmtree(workspace_root, ignore_errors=True)


def run_agent_team_pipeline(project_id: UUID, session_factory) -> None:
    """ORCHESTRATOR=agent-team: a tester agent writes tests from the description, then the builder makes them pass."""
    run_agent_pipeline(project_id, session_factory, with_tester=True)


def _collect_files(executor) -> dict:
    """Every text file of the generated project, {path: content}, read through the executor.

    Skips database files and caches (binary or regenerated). A file that can't be read as text is skipped rather
    than failing the whole save.
    """
    files = {}
    for path in executor.list_files():
        if path.endswith(agent.DATABASE_FILES) or "__pycache__" in path.split("/"):
            continue
        try:
            files[path] = executor.read_file(path)
        except Exception:
            logger.warning("Could not read %s for the project download", path)
    return files


def _count_tests(executor) -> int:
    """How many test functions the tests/test_*.py files contain, read through the executor."""
    return sum(executor.read_file(path).count("\ndef test_") for path in executor.list_files("tests")
               if Path(path).name.startswith("test_") and path.endswith(".py"))


def _count_requirements(executor) -> int:
    """Numbered requirement lines in the tester's tests/REQUIREMENTS.md, read through the executor."""
    if "tests/REQUIREMENTS.md" not in executor.list_files("tests"):
        return 0
    return len(agent.requirement_numbers(executor.read_file("tests/REQUIREMENTS.md")))


def _save_usage(project: Project, meter) -> None:
    """One task row with what the models used, so tokens and cost are visible without a database change."""
    totals = meter.totals()
    if not totals["requests"]:
        return
    tokens = totals["input_tokens"] + totals["output_tokens"]
    if totals["cost_complete"]:
        cost = f"${totals['cost_usd']:.4f}"
    else:
        cost = f"at least ${totals['cost_usd']:.4f}" if totals["cost_usd"] else "cost not reported"
    project.tasks.append(Task(
        id=uuid4(), position=len(project.tasks) + 1,
        name=f"Model usage: {totals['requests']} requests, {tokens:,} tokens ({totals['cached_tokens']:,} cached), {cost}"[:200],
        description="What the AI models used for this project", tool="orchestrator", status="completed", attempts=1,
        output=json.dumps(totals),
    ))


def _model_note(chosen: str, *outcomes) -> str:
    """Which model did the work, and say so honestly if the fallback had to take over."""
    used = sorted({o.get("model", chosen) for o in outcomes} - {chosen})
    if not used:
        return chosen
    return f"{chosen}, with {', '.join(used)} taking over when it was overloaded"


def _review_note(reviews: list) -> str:
    """One sentence on the feedback loop for the summary, e.g. ' Feedback loop: the tester corrected test_r10_x.'"""
    if not reviews:
        return ""
    verdicts = []
    for review in reviews:
        parts = []
        if review["fixed"]:
            parts.append(f"corrected {', '.join(review['fixed'])}")
        if review["upheld"]:
            parts.append(f"upheld {', '.join(review['upheld'])}")
        verdicts.append(" and ".join(parts) or f"could not finish reviewing {', '.join(review['tests'])}")
    return f" Feedback loop: the tester re-checked the failing tests and {'; then '.join(verdicts)}."


def _describe_step(event) -> tuple[str, str]:
    """A readable task name and output for one agent step."""
    tool, args, result = event["tool"], event["args"], event["result"]
    if tool == "write_file":
        return f"Wrote {args.get('path', '?')}", args.get("content", "")
    if tool == "read_file":
        return f"Read {args.get('path', '?')}", result[:2000]
    if tool == "list_files":
        return "Listed the project files", result
    if tool == "run_tests":
        return f"Ran the tests: {_last_line(result)}", result[-2000:]
    if tool in ("fix_test", "uphold_test"):
        test = args.get("test", "?")
        if result.startswith(("REFUSED", "ERROR")):
            return f"Could not record a decision on {test}", result[:2000]
        return f"{'Fixed' if tool == 'fix_test' else 'Upheld'} {test}", str(args.get("reason", ""))[:2000]
    return tool, result[:2000]


def _step_status(event, tester: bool = False) -> str:
    """Red for refused or broken tool calls and for failing test runs; green otherwise.
    For the tester, failing tests are expected (nothing is built yet): only tests that don't load are red."""
    result = event["result"]
    if result.startswith(("ERROR", "REFUSED", "TIMEOUT")):
        return "failed"
    if event["tool"] == "run_tests":
        if tester:
            return "failed" if "error" in _last_line(result) else "completed"
        if not agent.tests_pass(result):
            return "failed"
    return "completed"


def _last_line(text: str) -> str:
    text = text.strip()
    return text.splitlines()[-1] if text else "(no output)"

def get_pipeline():
    """Dependency so tests can swap the pipeline out.
    ORCHESTRATOR=agent: the coding agent with built-in tests. ORCHESTRATOR=agent-team: tester + builder agents."""
    mode = os.getenv("ORCHESTRATOR")
    if mode == "agent":
        return run_agent_pipeline
    if mode == "agent-team":
        return run_agent_team_pipeline
    return run_pipeline

def _touch(project: Project) -> None:
    project.updated_at = datetime.now(timezone.utc)


def _public_reason(error: Exception) -> str:
    """Why a build stopped, safe to show anyone: a raw exception can contain keys or internal details."""
    if isinstance(error, agent.model_client.ModelUnavailable):
        return error.public
    return "An internal error stopped the build."


def _mark_failed(db, project_id: UUID, error: Exception | None = None, executor=None, meter=None) -> None:
    """Mark a project failed. With `error` (an agent run that crashed), also say why and save what was built so far."""
    try:
        project = db.get(Project, project_id)
        if project is not None:
            project.status = "failed"
            if error is not None:
                reason = _public_reason(error)
                project.tasks.append(Task(
                    id=uuid4(), position=len(project.tasks) + 1, name=f"Build stopped: {reason}"[:200],
                    description="The run ended early", tool="orchestrator", status="failed", attempts=1,
                ))
                if meter is not None:
                    _save_usage(project, meter)
                files = None
                if executor is not None:
                    try:
                        files = _collect_files(executor)
                    except Exception:  # the sandbox may be gone: still record the failure honestly
                        logger.exception("Could not save partial files for project %s", project_id)
                if files:
                    project.artifact = files
                project.summary = f"The build stopped. {reason}" + (
                    " The files written so far are in the download." if files else "")
            _touch(project)
            db.commit()
    except Exception:
        logger.exception("Could not mark project %s as failed", project_id)
        db.rollback()
